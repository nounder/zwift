//! Pure Zig source generator. Reflect the actual core signatures into a C importer
//! surface; generate Swift ABI declarations and Swift @main App entry points.
const std = @import("std");
const core = @import("core.zig");
fn ctype(comptime T: type) []const u8 {
    if (T == void) return "void";
    if (T == u64) return "uint64_t";
    if (T == u32) return "uint32_t";
    if (T == usize) return "size_t";
    if (T == core.Environment) return "ZWEnvironment";
    if (T == core.Stats) return "ZWStats";
    if (T == core.TodoInfo) return "ZWTodoInfo";
    if (T == core.Change) return "ZWChange";
    if (T == *anyopaque or T == ?*anyopaque) return "void *";
    if (T == *const anyopaque) return "const void *";
    if (T == [*]const u8) return "const uint8_t *";
    if (T == ?[*]u8) return "uint8_t *";
    @compileError("Unmapped ABI type: " ++ @typeName(T));
}
fn header() []const u8 {
    comptime {
        @setEvalBranchQuota(100000);
        var result: []const u8 = "// Generated by lab/generate.zig. Do not edit.\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\ntypedef void (*ZWChange)(void *, uint64_t);\n";
        for (.{ .{ core.Environment, "ZWEnvironment" }, .{ core.Stats, "ZWStats" }, .{ core.TodoInfo, "ZWTodoInfo" } }) |entry| {
            result = result ++ "typedef struct {\n";
            for (@typeInfo(entry[0]).@"struct".fields) |f| result = result ++ "    " ++ ctype(f.type) ++ " " ++ f.name ++ ";\n";
            result = result ++ "} " ++ entry[1] ++ ";\n";
        }
        for (@typeInfo(core).@"struct".decls) |decl| {
            if (!std.mem.startsWith(u8, decl.name, "zw_")) continue;
            const f = @typeInfo(@TypeOf(@field(core, decl.name))).@"fn";
            result = result ++ ctype(f.return_type.?) ++ " " ++ decl.name ++ "(";
            for (f.params, 0..) |p, i| {
                if (i != 0) result = result ++ ", ";
                result = result ++ ctype(p.type.?) ++ " arg" ++ std.fmt.comptimePrint("{d}", .{i});
            }
            if (f.params.len == 0) result = result ++ "void";
            result = result ++ ");\n";
        }
        return result;
    }
}
pub fn main(init: std.process.Init) !void {
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    if (args.len != 2) return error.ExpectedOutputDirectory;
    const dir = try std.Io.Dir.cwd().createDirPathOpen(init.io, args[1], .{});
    defer dir.close(init.io);
    try dir.writeFile(init.io, .{ .sub_path = "Bridge.h", .data = comptime header() });
    const view_schema = @import("views/schema.zig");
    try dir.writeFile(init.io, .{ .sub_path = "GeneratedViews.swift", .data = comptime view_schema.emit(&@import("views/apps.zig").views) });
    const abi = @import("abi/schema.zig");
    try dir.writeFile(init.io, .{ .sub_path = "NativeABI.swift", .data = comptime abi.declarations() });
    try dir.writeFile(init.io, .{ .sub_path = "ABIReferences.swift", .data = comptime abi.references() });
    try dir.writeFile(init.io, .{ .sub_path = "ABIManifest.json", .data = comptime abi.manifest() });
    try dir.writeFile(init.io, .{ .sub_path = "NativeABI.s", .data = comptime abi.assembly() });
    inline for (.{ .{ "Todo", "TodoRoot", "0" }, .{ "Editor", "EditorRoot", "1" }, .{ "Browser", "BrowserRoot", "2" } }) |app| {
        try dir.writeFile(init.io, .{ .sub_path = app[0] ++ "App.swift", .data = "// Generated by pure Zig; swiftc supplies the App/View protocol machinery.\n" ++
            "import SwiftUI\nimport AppKit\n" ++
            "@main struct Zwift" ++ app[0] ++ "App: App {\n" ++
            "    @NSApplicationDelegateAdaptor(LabAppDelegate.self) private var delegate\n" ++
            "    var body: some Scene {\n" ++
            "        WindowGroup(\"Zwift " ++ app[0] ++ "\") { LabShell(kind: " ++ app[2] ++ ") { " ++ app[1] ++ "() } }\n" ++
            "        .defaultSize(width: 840, height: 620)\n" ++
            "    }\n}\n" });
    }
}
